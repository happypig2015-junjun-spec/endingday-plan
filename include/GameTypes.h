//==============================================================================
// GameTypes.h
//------------------------------------------------------------------------------
// 游戏全部核心数据结构（纯数据 / POD 聚合体）。
//
// 设计目标：
//   1. 剧情与逻辑彻底分离——StoryData.cpp 只填数据，GameEngine 只跑逻辑；
//   2. 所有结构体均为“聚合体（aggregate）”，可在 C++20 下使用
//      “指定初始化器（designated initializer）”，例如：
//          Scene{ .id = "hub", .title = "避难所", .choices = { ... } }
//      字段顺序、含义一目了然，新增剧情时几乎不可能写错；
//   3. 新增任何内容（线索 / 场景 / 结局 / 条件类型）都无需改动引擎主干，
//      体现“高可拓展性”。
//==============================================================================
#ifndef GAME_TYPES_H
#define GAME_TYPES_H

#include <string>
#include <vector>

//==============================================================================
// 线索阶段（三档）
//   Basic    基础线索：描述“发生了什么”（现象层）
//   Advanced 进阶线索：揭示“谁在做、为什么”（阴谋层）
//   Supreme  高级线索：触及“末日的本质”（真相层）
//==============================================================================
enum class ClueTier
{
    Basic,    // 基础线索
    Advanced, // 进阶线索
    Supreme,  // 高级线索
    Item      // 随身物品/道具：把各分支“关联”起来的钥匙类物品，
              // 不计入三阶段推理进度，但会显示在线索本“随身物品”分区
};

//==============================================================================
// Clue —— 一条线索
//   id     线索唯一编号（如 "B1" / "A2" / "S3"），
//          全剧情的条件、授予、检索都通过该 id 进行；
//   tier   所属阶段；
//   name   线索名称（线索本 / 获得提示中展示）；
//   detail 线索详情（线索本中展示，记录用命换来的关键信息）。
//==============================================================================
struct Clue
{
    std::string id;
    ClueTier    tier = ClueTier::Basic;
    std::string name;
    std::string detail;
};

//==============================================================================
// Choice —— 场景中的一个可选项
//   text         选项文本；
//   target       选择后跳转的场景 id；
//                留空（""）表示返回中枢场景 "hub"；
//                特殊值 __quit 表示退出游戏；
//   grantedClue  选择后立即获得的线索 id；留空表示不获得线索；
//   requireAll   “显示条件”：玩家必须已拥有其中【全部】线索，该选项才出现；
//   requireNone  “显示条件”：玩家必须【均未拥有】其中线索，该选项才出现；
//   endingId     非空时，选择后不跳转场景，而是直接触发对应结局。
//==============================================================================
struct Choice
{
    std::string              text;
    std::string              target = "";
    std::string              grantedClue = "";
    std::vector<std::string> requireAll = {};
    std::vector<std::string> requireNone = {};
    std::string              endingId = "";
};

//==============================================================================
// Scene —— 一个剧情场景（节点）
//   id         场景唯一编号；
//   title      场景标题（进入时以加粗形式展示），留空则不显示；
//   paragraphs 正文段落（每一个元素为一段，逐段逐字播放）；
//   choices     该场景下的全部选项（引擎会按条件过滤后再展示）；
//   isDeath     “死亡场景”标记：true 表示走到终点，正文后不显示选项，
//              而是发动“时间回溯”——回到中枢 "hub"，线索全部保留。
//==============================================================================
struct Scene
{
    std::string              id;
    std::string              title = "";
    std::vector<std::string> paragraphs = {};
    std::vector<Choice>      choices = {};
    bool                     isDeath = false;
};

//==============================================================================
// Ending —— 一个结局
//   id         结局唯一编号（与 Choice.endingId 对应）；
//   title      结局标题；
//   paragraphs 结局正文（逐字播放）。
//==============================================================================
struct Ending
{
    std::string              id;
    std::string              title;
    std::vector<std::string> paragraphs;
};

#endif // GAME_TYPES_H
